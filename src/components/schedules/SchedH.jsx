const updateRow = (setter, rowIndex, columnIndex, value) => {
  setter((prevRows) =>
    prevRows.map((row, index) => {
      if (index !== rowIndex) {
        return row;
      }

      const updatedRow = [...row];

      // Update the edited cell
      updatedRow[columnIndex] = value;

      // Convert formatted values like "1,234" to numbers
      const toNumber = (val) => {
        if (val === null || val === undefined || val === "") {
          return 0;
        }

        const parsed = parseFloat(String(val).replace(/,/g, ""));

        return Number.isFinite(parsed) ? parsed : 0;
      };

      // Format calculated values
      const formatVal = (val) => {
        if (!Number.isFinite(val) || val === 0) {
          return "-";
        }

        return Math.round(val).toLocaleString();
      };

      // =====================================================
      // BLUE COLUMN 6
      // TOTAL LABOR
      // 3 + 4 + 5
      // =====================================================
      const totalLabor =
        toNumber(updatedRow[3]) +
        toNumber(updatedRow[4]) +
        toNumber(updatedRow[5]);

      // =====================================================
      // BLUE COLUMN 12
      // DIRECT COSTS
      // 6 + 7 + 8 + 9 + 10 + 11
      // =====================================================
      const directCosts =
        totalLabor +
        toNumber(updatedRow[7]) +
        toNumber(updatedRow[8]) +
        toNumber(updatedRow[9]) +
        toNumber(updatedRow[10]) +
        toNumber(updatedRow[11]);

      // =====================================================
      // BLUE COLUMN 19
      // DIRECT COSTS PLUS O/H & FRINGE
      // 12 + 13 + 14 + 15 + 16 + 17 + 18
      // =====================================================
      const directPlusOH =
        directCosts +
        toNumber(updatedRow[13]) +
        toNumber(updatedRow[14]) +
        toNumber(updatedRow[15]) +
        toNumber(updatedRow[16]) +
        toNumber(updatedRow[17]) +
        toNumber(updatedRow[18]);

      // =====================================================
      // BLUE COLUMN 20
      // G&A BASE (VALUE ADDED)
      // 19 - (8 + 10 + 11 + 18)
      // =====================================================
      const gaBase =
        directPlusOH -
        (toNumber(updatedRow[8]) +
          toNumber(updatedRow[10]) +
          toNumber(updatedRow[11]) +
          toNumber(updatedRow[18]));

      // =====================================================
      // COLUMN 21 IS EDITABLE
      // =====================================================
      const gaApplied = toNumber(updatedRow[21]);

      // =====================================================
      // BLUE COLUMN 22
      // TOTAL COSTS
      // 19 + 21
      // =====================================================
      const totalCosts = directPlusOH + gaApplied;

      // =====================================================
      // BLUE COLUMN 24
      // GRAND TOTAL
      // =====================================================
      const grandTotal = totalCosts;

      // =====================================================
      // UPDATE ONLY BLUE / CALCULATED COLUMNS
      // =====================================================

      updatedRow[6] = formatVal(totalLabor);
      updatedRow[12] = formatVal(directCosts);
      updatedRow[19] = formatVal(directPlusOH);
      updatedRow[20] = formatVal(gaBase);
      updatedRow[22] = formatVal(totalCosts);
      updatedRow[24] = formatVal(grandTotal);

      return updatedRow;
    }),
  );
};

function DataRow({ row, onChange, onDelete }) {
  return (
    <div className="flex h-[24px] overflow-hidden">
      {row.map((value, i) => {
        const isCalculated = calculatedColumns.includes(i);

        return (
          <div
            key={i}
            style={{
              width: widths[i],
              minWidth: widths[i],
              maxWidth: widths[i],
              backgroundColor: cellBg(i),
            }}
            className="box-border flex shrink-0 items-center border-r border-b border-[#444] px-[4px]"
          >
            {isCalculated ? (
              /* BLUE / CALCULATED */
              <span
                title={value}
                className="block w-full overflow-hidden whitespace-nowrap text-ellipsis text-right text-[10px]"
              >
                {value === "" ? "" : value || "-"}
              </span>
            ) : (
              /* EDITABLE */
              <input
                type="text"
                value={value === "-" ? "" : (value ?? "")}
                onChange={(e) => {
                  const newValue = e.target.value;

                  // ==========================================
                  // FIRST 3 COLUMNS = ANYTHING
                  // ==========================================
                  if (i < 3) {
                    onChange(i, newValue);
                    return;
                  }

                  // ==========================================
                  // REST = NUMBERS ONLY
                  // ==========================================
                  const numericValue = newValue.replace(/,/g, "");

                  if (/^-?\d*\.?\d*$/.test(numericValue)) {
                    onChange(i, newValue);
                  }
                }}
                className={`h-full w-full border-0 bg-transparent px-0 text-[10px] outline-none ${
                  i < 3 ? "text-left" : "text-right"
                }`}
              />
            )}
          </div>
        );
      })}

      {/* DELETE */}
      <div
        style={{
          width: 70,
          minWidth: 70,
          maxWidth: 70,
        }}
        className="flex shrink-0 items-center justify-center border-r border-b border-[#444] bg-white"
      >
        <button
          type="button"
          onClick={() => {
            const confirmed = window.confirm(
              "This account may be used in other schedules as well.\n\n" +
                "Deleting it from this schedule may affect other schedule calculations.\n\n" +
                "Are you sure you want to delete this row?",
            );

            if (confirmed) {
              onDelete();
            }
          }}
          className="rounded bg-red-600 px-2 py-[2px] text-[10px] font-bold text-white hover:bg-red-700"
        >
          Delete
        </button>
      </div>
    </div>
  );
}

