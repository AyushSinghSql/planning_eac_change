const calcTotal = (rows) => {
  const totals = Array(headers.length).fill("-");
  totals[0] = "";
  totals[1] = "";
  totals[2] = "";
  for (let col = 3; col < headers.length; col++) {
    let sum = 0;
    rows.forEach((r) => {
      if (r[col] && r[col] !== "-") {
        sum += parseFloat(String(r[col]).replace(/,/g, "")) || 0;
      }
    });
    totals[col] = sum === 0 ? "-" : Math.round(sum).toLocaleString();
  }
  return totals;
};

